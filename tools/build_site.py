#!/usr/bin/env python3
"""build_site.py -- generate the MkDocs site from the LaTeX modules and course_map.yaml.

    python3 -I tools/build_site.py            # convert + write mkdocs.yml, then `mkdocs build --strict`
    python3 -I tools/build_site.py --no-build # convert + write config only

Everything under site/docs/<module>/ and site/mkdocs.yml is GENERATED; edit the LaTeX or
course_map.yaml instead.  Hand-written site files live in site/docs/stylesheets and site/filters.

Enforced here (CONVENTIONS.md): instructor notes and solutions never enter the site, and every
macro in la.sty has an entry in site/macros.json.
"""
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import tex2md  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
DOCS = SITE / "docs"
PUBLIC = ("notes",)   # what the site publishes; tex2md can also convert "worksheet" and "homework" (add them here to publish them)
PRIVATE_PATTERNS = ("instructor", "solution")
CHAPTER = {1: "Linear Equations in Linear Algebra", 2: "Matrix Algebra", 3: "Determinants",
           4: "Vector Spaces", 5: "Eigenvalues and Eigenvectors", 6: "Orthogonality and Least Squares"}


def lint_macros():
    """Every macro/environment defined in la.sty must be mirrored in site/macros.json."""
    sty = (ROOT / "shared" / "la.sty").read_text()
    mj = json.loads((SITE / "macros.json").read_text())
    names = set(re.findall(r"\\newcommand\{\\(\w+)\}(?:\[\d\])?\{\\?(?:mathbb|blacksquare|ast|xrightarrow|\^|mathbf|langle|\{)", sty))
    # math-mode shortcuts section only
    section = sty.split("math shortcuts", 1)[1].split("running header", 1)[0]
    names = set(re.findall(r"\\newcommand\{\\(\w+)\}", section)) | set(re.findall(r"\\DeclareMathOperator\{\\(\w+)\}", section))
    missing = sorted(n for n in names if n not in mj)
    if missing:
        raise SystemExit("la.sty macros missing from site/macros.json: " + ", ".join(missing))
    extra = sorted(n for n in mj if n not in names)
    if extra:
        print("note: macros.json has entries not in la.sty:", ", ".join(extra))
    # amat is expanded by tex2md.py (MathJax cannot define environments from JSON)
    return mj


def built_modules(course):
    mods = []
    for m in course["modules"]:
        d = ROOT / "modules" / m["id"]
        if (d / "notes.tex").exists():
            mods.append(m)
    return mods


def write_mathjax(macros):
    js = f"""// GENERATED by tools/build_site.py from site/macros.json -- do not edit.
window.MathJax = {{
  tex: {{
    inlineMath: [["\\\\(", "\\\\)"]],
    displayMath: [["\\\\[", "\\\\]"]],
    processEscapes: true,
    processEnvironments: true,
    macros: {json.dumps(macros, indent=4)}
  }},
  options: {{ ignoreHtmlClass: ".*|", processHtmlClass: "arithmatex" }}
}};
document$.subscribe(() => {{
  MathJax.startup.output.clearCache();
  MathJax.typesetClear();
  MathJax.texReset();
  MathJax.typesetPromise();
}});
"""
    p = DOCS / "javascripts" / "mathjax.js"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(js)


def write_index(course, mods):
    C = course["course"]
    built = {m["id"] for m in mods}
    lines = [f"# {C['title']}", "", f"**{C['term']}.** Textbook: {C['textbook']}.", "",
             "Lecture notes for each section. Every page can also be downloaded as a PDF.", "",
             "| Section | Title | Tested | Notes |", "|---|---|---|---|"]
    for m in course["modules"]:
        if m["id"] in built:
            links = " · ".join(f"[Notes]({m['id']}/{k}.md)"
                               for k in PUBLIC if (ROOT / "modules" / m["id"] / f"{k}.tex").exists())
        else:
            links = "*coming soon*"
        lines.append(f"| {m['id']} | {m['title']} | {'yes' if m['tested'] else 'enrichment'} | {links} |")
    lines += ["", "Sections marked *enrichment* have full notes but are not on the exams; their homework is optional."]
    (DOCS / "index.md").write_text("\n".join(lines) + "\n")


def write_mkdocs(course, mods):
    C = course["course"]
    nav = [{"Home": "index.md"}]
    by_ch = {}
    for m in mods:
        by_ch.setdefault(m["chapter"], []).append(m)
    for ch in sorted(by_ch):
        entries = []
        for m in by_ch[ch]:
            pages = [{k.capitalize(): f"{m['id']}/{k}.md"} for k in PUBLIC
                     if (DOCS / m["id"] / f"{k}.md").exists()]
            entries.append({f"{m['id']} {m['title']}": pages})
        nav.append({f"Chapter {ch}: {CHAPTER[ch]}": entries})
    cfg = {
        "site_name": f"{C['title']} ({C['term']})",
        "docs_dir": "docs",
        "site_dir": "../build/site",
        "exclude_docs": "instructor*\n**/instructor*\nsolution*\n**/solution*\n",
        "theme": {
            "name": "material",
            "features": ["navigation.sections", "navigation.top", "toc.follow", "content.code.copy"],
            "palette": [
                {"scheme": "default", "toggle": {"icon": "material/brightness-7", "name": "Switch to dark mode"}},
                {"scheme": "slate", "toggle": {"icon": "material/brightness-4", "name": "Switch to light mode"}},
            ],
        },
        "markdown_extensions": [
            "admonition", "attr_list", "tables", "md_in_html",
            {"toc": {"permalink": True}},
            "pymdownx.details", "pymdownx.superfences",
            {"pymdownx.arithmatex": {"generic": True}},
        ],
        "extra_javascript": ["javascripts/mathjax.js", "https://unpkg.com/mathjax@3/es5/tex-mml-chtml.js"],
        "extra_css": ["stylesheets/extra.css"],
        "nav": nav,
    }
    header = "# GENERATED by tools/build_site.py from course_map.yaml -- do not edit.\n"
    (SITE / "mkdocs.yml").write_text(header + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, width=1000))


def privacy_check(root, label):
    bad = [p for p in root.rglob("*") if p.is_file() and any(t in p.name.lower() for t in PRIVATE_PATTERNS)]
    if bad:
        raise SystemExit(f"PRIVACY: private files found in {label}: {bad}")
    for p in root.rglob("*"):
        if p.suffix in {".html", ".md", ".txt", ".xml", ".json"} and p.is_file():
            txt = p.read_text(errors="ignore")
            if "not for students" in txt.lower() or "instructor notes" in txt.lower():
                raise SystemExit(f"PRIVACY: instructor marker text found in {p}")


def main(build=True):
    course = yaml.safe_load((ROOT / "course_map.yaml").read_text())
    macros = lint_macros()
    mods = built_modules(course)
    registries = {m["id"]: tex2md.build_registry(m["id"]) for m in mods}

    # fresh generated tree (keep hand-written stylesheets)
    for m in mods:
        shutil.rmtree(DOCS / m["id"], ignore_errors=True)
    n_pages = 0
    for m in mods:
        for kind in PUBLIC:
            src = ROOT / "modules" / m["id"] / f"{kind}.tex"
            if not src.exists():
                continue
            pdf = src.with_suffix(".pdf")
            out = DOCS / m["id"]
            out.mkdir(parents=True, exist_ok=True)
            if pdf.exists():
                shutil.copy(pdf, out / f"{kind}.pdf")
            tex2md.convert(m["id"], kind, registries, DOCS)
            n_pages += 1
    write_mathjax(macros)
    write_index(course, mods)
    write_mkdocs(course, mods)
    privacy_check(DOCS, "site/docs")
    print(f"generated {n_pages} pages for {len(mods)} modules")
    if build:
        r = subprocess.run(["mkdocs", "build", "--strict", "-f", str(SITE / "mkdocs.yml")])
        if r.returncode:
            raise SystemExit("mkdocs build failed")
        privacy_check(ROOT / "build" / "site", "build/site")
        print("site built in build/site (privacy check passed)")


if __name__ == "__main__":
    main(build="--no-build" not in sys.argv)
